"""Escala legada de espaçamento da UI."""

class Spacing:
    """Objeto simples com aliases de espaçamento em pixels."""

    def __init__(self):
        """Inicializa a escala legada de espaçamentos."""
        self.xs = 4
        self.sm = 8
        self.md = 16
        self.lg = 24
        self.xl = 32
        self.xxl = 48
        self.ul = 60
